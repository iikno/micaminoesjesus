// npm run seed:sql  -> writes server/migrations/007_seed_catalogo.sql from the static site data (src/data/*).
// npm run seed:sql -- --check  -> exits 1 if the committed file is out of date (used by the tests).
// The migration runs once on the next deploy (index.js migrates before listening) and is idempotent and
// non-destructive: dérej/seasons are upserted; retreats, team, calendar and verse rows that already exist
// (by slug / name / title+date / ref) are left untouched, so editors' changes are never overwritten.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import mysql from 'mysql2';
import { ENTITIES, snapshotOf } from '../lib/entities.js';
import { seedRows } from '../seed/rows.js';

const OUT = fileURLToPath(new URL('../migrations/007_seed_catalogo.sql', import.meta.url));
const esc = (v) => mysql.escape(v);
const PUB = ['status', 'live_from', 'published_snapshot'];
const cols = (row) => Object.keys(row).map((k) => `\`${k}\``).join(', ');
const vals = (row) => Object.values(row).map((v) => (typeof v === 'boolean' ? (v ? 'TRUE' : 'FALSE') : esc(v))).join(', ');

// Published snapshot without `id` (unknown until insert); a follow-up UPDATE adds it with JSON_SET.
function snap(key, row) {
  const e = ENTITIES[key];
  const parsed = { ...row, ...Object.fromEntries(e.json.map((k) => [k, row[k] == null ? null : JSON.parse(row[k])])) };
  const { id: _id, ...s } = snapshotOf(e, parsed);
  return JSON.stringify(s);
}
const pubVals = (key, row) => `${vals(row)}, 'publicado', UTC_TIMESTAMP(), ${esc(snap(key, row))}`;

// INSERT ... SELECT ... WHERE NOT EXISTS: skips rows already present without INSERT IGNORE (which would hide truncation errors).
const insertIfMissing = (key, row, where) => {
  const t = ENTITIES[key].table;
  return `INSERT INTO ${t} (${cols(row)}, ${PUB.join(', ')})\n  SELECT ${pubVals(key, row)} FROM DUAL\n  WHERE NOT EXISTS (SELECT 1 FROM ${t} WHERE ${where});`;
};
const fixIds = (t) => `UPDATE ${t} SET published_snapshot = JSON_SET(published_snapshot, '$.id', id)\n  WHERE published_snapshot IS NOT NULL AND JSON_EXTRACT(published_snapshot, '$.id') IS NULL;`;

export function buildSql() {
  const d = seedRows();
  const upsert = (t, rows, keys) => `INSERT INTO ${t} (${cols(rows[0])}) VALUES\n${rows.map((r) => `  (${vals(r)})`).join(',\n')}\nON DUPLICATE KEY UPDATE ${keys.map((k) => `\`${k}\` = VALUES(\`${k}\`)`).join(', ')};`;
  const counts = Object.fromEntries(Object.entries(d).map(([k, v]) => [k, v.length]));
  const tipos = d.retreats.reduce((a, r) => ({ ...a, [r.tipo]: (a[r.tipo] ?? 0) + 1 }), {});
  return [
    '-- GENERATED by `npm run seed:sql` from src/data/* — do not edit by hand.',
    '-- Catálogo original del sitio estático: dérej, temporadas, talleres/retiros/horas santas/estaciones,',
    '-- equipo, calendario y versículo. Idempotente y no destructivo (ver server/cli/gen-seed-sql.js).',
    `-- ${JSON.stringify(counts)} · retreats por tipo ${JSON.stringify(tipos)}`,
    'START TRANSACTION;',
    '',
    '-- Dérej y temporadas: configuración estructural, se sincronizan siempre.',
    upsert('derej', d.derej, Object.keys(d.derej[0]).filter((k) => k !== 'slug')),
    upsert('seasons', d.seasons, ['name', 'sort']),
    '',
    '-- Talleres, retiros, horas santas y estaciones (retreats.tipo).',
    ...d.retreats.map((r) => insertIfMissing('retreats', r, `slug = ${esc(r.slug)}`)),
    fixIds('retreats'),
    '',
    '-- Equipo.',
    ...d.team.map((m) => insertIfMissing('team', m, `name = ${esc(m.name)}`)),
    fixIds('team_members'),
    '',
    '-- Calendario (entradas libres; un editor puede ligarlas a un retiro desde el panel).',
    ...d.sessions.map((s) => insertIfMissing('sessions', s, `title = ${esc(s.title)} AND starts_on = ${esc(s.starts_on)}`)),
    fixIds('retreat_sessions'),
    '',
    '-- Versículo de la portada.',
    ...d.verses.map((v) => insertIfMissing('verses', v, `ref = ${esc(v.ref)}`)),
    fixIds('verses'),
    '',
    `INSERT INTO audit_log (action, entity, diff) VALUES ('seed', 'catalogo', ${esc(JSON.stringify({ source: '007_seed_catalogo.sql', counts, tipos }))});`,
    'COMMIT;',
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const sql = buildSql();
  if (process.argv.includes('--check')) {
    let cur = '';
    try { cur = readFileSync(OUT, 'utf8'); } catch { /* missing */ }
    // autocrlf checkouts on Windows make the file CRLF; the committed blob is LF.
    if (cur.replace(/\r\n/g, '\n') !== sql) { console.error('007_seed_catalogo.sql is out of date: run npm run seed:sql'); process.exit(1); }
  } else {
    writeFileSync(OUT, sql);
    console.log(`wrote ${OUT} (${(sql.length / 1024).toFixed(0)} KB)`);
  }
}
